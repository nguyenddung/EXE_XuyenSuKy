import { expect, test } from '@playwright/test'

test.use({ storageState: { cookies: [], origins: [] } })

test('signed-out visitors are sent to sign-in and return to the page they wanted', async ({ page }) => {
  await page.goto('/home')
  await expect(page).toHaveURL(/\/dang-nhap$/)
  await expect(page.getByRole('heading', { name: 'Đăng nhập Xuyên Sử Ký' })).toBeVisible()
  await page.getByRole('button', { name: 'Điền tài khoản mẫu' }).click()
  await page.locator('.login-form button[type=submit]').click()
  await page.locator('.grade-onboarding .button-primary').click()
  await expect(page).toHaveURL(/\/home$/)
  await expect(page.getByRole('button', { name: 'Tài khoản' })).toContainText('Minh')
  await expect(page.locator('.dashboard-guest-banner')).toHaveCount(0)
  await page.getByRole('button', { name: 'Tài khoản' }).click()
  await page.getByRole('link', { name: 'Đăng xuất' }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/home')
  await expect(page).toHaveURL(/\/dang-nhap$/)
})

test('landing never opens the app by itself; guest mode is an explicit choice', async ({ page }) => {
  await page.goto('/')
  const header = page.getByRole('navigation', { name: 'Điều hướng chính' })
  await expect(header.getByRole('link', { name: 'Trang chủ' })).toHaveCount(0)
  await header.getByRole('link', { name: 'Bắt đầu học' }).click()
  await expect(page).toHaveURL(/\/dang-nhap$/)
  await page.getByRole('button', { name: /Học thử không cần tài khoản/ }).click()
  await page.locator('.grade-onboarding .button-primary').click()
  await expect(page).toHaveURL(/\/home$/)
  await expect(page.locator('.dashboard-guest-banner')).toContainText('Bạn đang học thử')
  await expect(page.locator('.dashboard-rank.is-me')).toContainText('Bạn (khách)')
})

test('an era chosen while signed out opens its lesson after signing in', async ({ page }) => {
  await page.goto('/')
  await page.locator('.landing-hero .dashboard-era').filter({ hasText: 'Thời Lý' }).click()
  await expect(page).toHaveURL(/\/dang-nhap$/)
  await page.getByRole('button', { name: /Học thử không cần tài khoản/ }).click()
  await page.locator('.grade-onboarding .button-primary').click()
  await expect(page).toHaveURL(/\/home#library$/)
  await expect(page.locator('#dataset-reader-title')).toContainText('thời Lý')
})

test('a sign-in kept forever by an older build opens the landing page as a visitor, with progress intact', async ({ page }) => {
  await page.addInitScript(() => localStorage.getItem('xuyen-su-ky-demo-v1') || localStorage.setItem('xuyen-su-ky-demo-v1', JSON.stringify({ loggedIn: true, userId: 'minh@xuyensuki.vn', name: 'Minh', gradeSelected: true, grade: 8, completedActivities: [], earnedXp: 90 })))
  await page.goto('/')
  const header = page.getByRole('navigation', { name: 'Điều hướng chính' })
  await expect(header.getByRole('link', { name: 'Đăng nhập' })).toBeVisible()
  await expect(header).not.toContainText('Minh')
  await page.goto('/home')
  await expect(page).toHaveURL(/\/dang-nhap$/)
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('xuyen-su-ky-demo-v1')!))
  expect(saved).toMatchObject({ grade: 8, earnedXp: 90 })
})

test('a sign-in lasts for the browser session unless remembered; the header shows the account', async ({ page, context }) => {
  await page.goto('/dang-nhap')
  await page.getByRole('button', { name: 'Điền tài khoản mẫu' }).click()
  await page.locator('.login-form button[type=submit]').click()
  await page.locator('.grade-onboarding .button-primary').click()
  await expect(page).toHaveURL(/\/home$/)
  await page.goto('/')
  const account = page.getByRole('button', { name: 'Tài khoản: Minh' })
  await expect(account).toBeVisible()
  await account.click()
  await expect(page.getByRole('menu')).toContainText('Tài khoản học sinh')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)

  // A new tab of a fresh browser session starts signed out.
  const fresh = await context.newPage()
  await fresh.goto('/')
  await expect(fresh.getByRole('navigation', { name: 'Điều hướng chính' }).getByRole('link', { name: 'Đăng nhập' })).toBeVisible()
  await fresh.goto('/dang-nhap')
  await fresh.getByRole('button', { name: 'Điền tài khoản mẫu' }).click()
  await fresh.getByLabel(/Ghi nhớ đăng nhập/).check()
  await fresh.locator('.login-form button[type=submit]').click()
  await expect(fresh).toHaveURL(/\/home$/)

  const later = await context.newPage()
  await later.goto('/')
  await expect(later.getByRole('button', { name: 'Tài khoản: Minh' })).toBeVisible()
  await later.getByRole('button', { name: 'Tài khoản: Minh' }).click()
  await later.getByRole('menuitem', { name: 'Đăng xuất' }).click()
  await expect(later.getByRole('navigation', { name: 'Điều hướng chính' }).getByRole('link', { name: 'Đăng nhập' })).toBeVisible()
  await later.goto('/home')
  await expect(later).toHaveURL(/\/dang-nhap$/)
})
