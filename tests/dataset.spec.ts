test('grade 12 selection survives reload; reader is usable on mobile and backend errors can retry', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/home')
  await page.locator('.class-card').filter({ has: page.getByRole('heading', { name: 'Lớp 12', exact: true }) }).getByRole('button').click()
  await expect(page.locator('.dataset-recommendation')).toContainText('LỚP 12')
  await page.reload()
  await expect(page.locator('.dataset-recommendation')).toContainText('LỚP 12')
  await page.locator('.dataset-recommendation button').click()
  await expect(page.locator('#dataset-reader-title')).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.locator('.dataset-reader').evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(page.locator('.dataset-recommendation button')).toBeFocused()
  expect(errors).toEqual([])
  await page.route('**/api/metadata', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":{"code":"DATASET_UNAVAILABLE"}}' }))
  await page.reload()
  await expect(page.locator('.dataset-status')).toContainText('Chưa đọc được dataset')
  await page.unroute('**/api/metadata')
  await page.getByRole('button', { name: 'Kết nối lại' }).click()
  await expect(page.locator('.dataset-stats')).toContainText('130')
})
